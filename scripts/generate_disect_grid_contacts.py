"""Generate a mesh-SDF variant of the existing DiSECt contact law (same force/scattering).

Only distance lookup changes. Frank-Wolfe edge search, interpolation, friction,
damping and spring damage stay those of the vendored source.
"""
import ast
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]/'backends/mujoco/third_party/disect/disect/dflex'
NAMES={'knife_sdf','knife_sdf_grad','edge_knife_sdf','edge_knife_sdf_grad','edge_knife_sdf_collision','eval_spring_sdf_contacts'}
def generate():
 tree=ast.parse((ROOT/'sim.py').read_text());nodes=[n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name in NAMES]
 class Convert(ast.NodeTransformer):
  def visit_FunctionDef(self,n):
   old=n.name;self.generic_visit(n);n.name='grid_'+old
   arg=ast.arg(arg='grid',annotation=ast.parse('df.tensor(float)',mode='eval').body)
   if old=='eval_spring_sdf_contacts':
    k=next(i for i,a in enumerate(n.args.args) if a.arg=='particle_f');n.args.args.insert(k,arg)
   else:n.args.args.append(arg)
   if old=='knife_sdf':n.body=ast.parse('return sample_grid_sdf(point, grid) - radius').body
   return n
  def visit_Call(self,n):
   self.generic_visit(n)
   if isinstance(n.func,ast.Name) and n.func.id in NAMES:
    n.func.id='grid_'+n.func.id;n.args.append(ast.Name(id='grid',ctx=ast.Load()))
   return n
 body=[Convert().visit(n) for n in nodes]
 text=ast.unparse(ast.fix_missing_locations(ast.Module(body=body,type_ignores=[])))
 header='''# Generated by scripts/generate_disect_grid_contacts.py. Preserve upstream license.
import disect.dflex.adjoint as df
from .sim import knife_contact_force

@df.func
def grid_value(grid: df.tensor(float), ix:int, iy:int, iz:int):
    ny=int(df.load(grid,1));nz=int(df.load(grid,2))
    return df.load(grid,9+(ix*ny+iy)*nz+iz)

@df.func
def sample_grid_sdf(point:df.float3,grid:df.tensor(float)):
    nx=int(df.load(grid,0));ny=int(df.load(grid,1));nz=int(df.load(grid,2))
    ox=df.load(grid,3);oy=df.load(grid,4);oz=df.load(grid,5)
    dx=df.load(grid,6);dy=df.load(grid,7);dz=df.load(grid,8)
    x=df.clamp((point[0]-ox)/dx,0.,float(nx-1)-0.0001)
    y=df.clamp((point[1]-oy)/dy,0.,float(ny-1)-0.0001)
    z=df.clamp((point[2]-oz)/dz,0.,float(nz-1)-0.0001)
    ix=int(x);iy=int(y);iz=int(z)
    fx=x-float(ix);fy=y-float(iy);fz=z-float(iz)
    a=grid_value(grid,ix,iy,iz)*(1.-fx)+grid_value(grid,ix+1,iy,iz)*fx
    b=grid_value(grid,ix,iy+1,iz)*(1.-fx)+grid_value(grid,ix+1,iy+1,iz)*fx
    c=grid_value(grid,ix,iy,iz+1)*(1.-fx)+grid_value(grid,ix+1,iy,iz+1)*fx
    d=grid_value(grid,ix,iy+1,iz+1)*(1.-fx)+grid_value(grid,ix+1,iy+1,iz+1)*fx
    value=((1.-fy)*a+fy*b)*(1.-fz)+((1.-fy)*c+fy*d)*fz
    outside=point-df.float3(ox+x*dx,oy+y*dy,oz+z*dz)
    return value+df.length(outside)

'''
 (ROOT/'grid_contact.py').write_text(header+text+'\n')
if __name__=='__main__':generate()
